namespace EricksonLopez.Specification;

/// <summary>
/// Specifies the ordering direction for a query specification order clause.
/// </summary>
public enum OrderDirection
{
    /// <summary>Orders results in ascending order, from smallest to largest.</summary>
    Ascending = 0,

    /// <summary>Orders results in descending order, from largest to smallest.</summary>
    Descending = 1
}
